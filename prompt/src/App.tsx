import { useState, useEffect, useRef } from 'react';
import './index.css';

interface Sentence {
  time: number;
  slide: number;
  text: string;
}

interface PrompterData {
  title: string;
  duration: number;
  sentences: Sentence[];
}

function parseLrc(lrcContent: string): Sentence[] {
  const lines = lrcContent.split('\n');
  const sentences: Sentence[] = [];
  let currentSlide = 1;

  for (const line of lines) {
    if (!line.trim()) continue;
    
    // Parse [mm:ss.xx]
    const timeMatch = line.match(/\[(\d{2}):(\d{2}\.\d{2})\]/);
    if (!timeMatch) continue;
    
    const minutes = parseInt(timeMatch[1], 10);
    const seconds = parseFloat(timeMatch[2]);
    const timeInSeconds = minutes * 60 + seconds;
    
    // Parse [slide=X]
    const slideMatch = line.match(/\[slide=(\d+)\]/);
    if (slideMatch) {
      currentSlide = parseInt(slideMatch[1], 10);
    }
    
    // Extract text (remove tags)
    let text = line.replace(/\[\d{2}:\d{2}\.\d{2}\]/g, '');
    text = text.replace(/\[slide=\d+\]/g, '').trim();
    
    if (text) {
      sentences.push({ time: timeInSeconds, slide: currentSlide, text });
    }
  }
  
  return sentences;
}

export default function App() {
  const [data, setData] = useState<PrompterData | null>(null);
  const [isPlaying, setIsPlaying] = useState(false);
  const [elapsedTime, setElapsedTime] = useState(0);
  const [fontSize, setFontSize] = useState(48); // default font size
  const [currentIndex, setCurrentIndex] = useState(0);
  
  const timerRef = useRef<number | null>(null);
  const lastTickRef = useRef<number>(0);

  // Stop timer on unmount
  useEffect(() => {
    return () => {
      if (timerRef.current) cancelAnimationFrame(timerRef.current);
    };
  }, []);

  // Timer logic
  useEffect(() => {
    if (isPlaying) {
      lastTickRef.current = performance.now();
      const tick = (now: number) => {
        const delta = (now - lastTickRef.current) / 1000;
        lastTickRef.current = now;
        setElapsedTime((prev) => {
          const newTime = prev + delta;
          // Update current index based on time
          if (data) {
            let nextIndex = data.sentences.findIndex(s => s.time > newTime) - 1;
            if (nextIndex < 0 && newTime < data.sentences[0]?.time) nextIndex = 0;
            if (nextIndex === -2) nextIndex = data.sentences.length - 1; // All sentences past
            if (nextIndex >= 0 && nextIndex !== currentIndex) {
                setCurrentIndex(nextIndex);
            }
          }
          return newTime;
        });
        timerRef.current = requestAnimationFrame(tick);
      };
      timerRef.current = requestAnimationFrame(tick);
    } else {
      if (timerRef.current) {
        cancelAnimationFrame(timerRef.current);
        timerRef.current = null;
      }
    }
  }, [isPlaying, data, currentIndex]);

  const handleFileUpload = async (event: React.ChangeEvent<HTMLInputElement>) => {
    const file = event.target.files?.[0];
    if (!file) return;
    
    if (file.name.endsWith('.lrc')) {
      const text = await file.text();
      const sentences = parseLrc(text);
      setData({
        title: file.name.replace('.lrc', ''),
        duration: 300, // Default to 5 mins if no JSON is loaded yet
        sentences
      });
      setElapsedTime(0);
      setCurrentIndex(0);
      setIsPlaying(false);
    } else if (file.name.endsWith('.json')) {
      // Allow loading JSON to update duration/metadata
      const text = await file.text();
      try {
        const json = JSON.parse(text);
        setData(prev => prev ? { ...prev, duration: json.duration, title: json.title || prev.title } : null);
      } catch (e) {
        console.error("Invalid JSON");
      }
    }
  };

  const togglePlay = () => setIsPlaying(!isPlaying);
  const reset = () => {
    setIsPlaying(false);
    setElapsedTime(0);
    setCurrentIndex(0);
  };
  
  const formatTime = (secs: number) => {
    const m = Math.floor(Math.max(0, secs) / 60);
    const s = Math.floor(Math.max(0, secs) % 60);
    return `${m.toString().padStart(2, '0')}:${s.toString().padStart(2, '0')}`;
  };

  if (!data) {
    return (
      <div className="flex flex-col items-center justify-center min-h-screen p-8 text-center bg-prompter-bg">
        <h1 className="text-4xl font-bold mb-8 text-prompter-accent">Conference Prompt</h1>
        <p className="mb-8 text-xl text-gray-400">Please upload the .lrc file generated by the python script.</p>
        <label className="px-6 py-3 bg-prompter-accent text-black rounded-lg cursor-pointer hover:bg-green-400 font-bold text-lg">
          Upload .lrc file
          <input type="file" accept=".lrc" className="hidden" onChange={handleFileUpload} />
        </label>
        <p className="mt-4 text-gray-500">(Optionally upload .json afterwards to set exact duration)</p>
      </div>
    );
  }

  const remainingTime = data.duration - elapsedTime;
  let timerColor = 'text-green-500';
  if (remainingTime < 0) timerColor = 'text-red-500';
  else if (remainingTime <= 30) timerColor = 'text-yellow-500';

  const currentSentence = data.sentences[currentIndex];
  const prevSentence = currentIndex > 0 ? data.sentences[currentIndex - 1] : null;
  const nextSentence = currentIndex < data.sentences.length - 1 ? data.sentences[currentIndex + 1] : null;
  
  const totalSlides = Math.max(...data.sentences.map(s => s.slide));

  return (
    <div className="flex flex-col h-screen overflow-hidden">
      {/* Top Bar */}
      <div className="flex justify-between items-center p-4 bg-slate-900 border-b border-slate-700">
        <div className="text-xl font-bold text-gray-300">
          Slide {currentSentence?.slide || 1} / {totalSlides}
        </div>
        <div className={`text-3xl font-mono font-bold ${timerColor}`}>
          {formatTime(elapsedTime)} / {formatTime(data.duration)}
        </div>
        <div className="flex gap-2">
          <button onClick={() => setFontSize(f => Math.max(24, f - 4))} className="p-2 bg-slate-700 rounded text-xl w-12 h-12 flex items-center justify-center">-</button>
          <button onClick={() => setFontSize(f => Math.min(120, f + 4))} className="p-2 bg-slate-700 rounded text-xl w-12 h-12 flex items-center justify-center">+</button>
        </div>
      </div>

      {/* Prompter Area */}
      <div className="flex-1 flex flex-col justify-center px-8 py-4 overflow-hidden relative">
        
        {/* Previous */}
        <div 
          className="absolute top-8 left-8 right-8 opacity-30 blur-[1px] transition-all duration-500 line-clamp-2"
          style={{ fontSize: `${fontSize * 0.6}px`, lineHeight: 1.4 }}
        >
          {prevSentence?.text}
        </div>

        {/* Current */}
        <div 
          className="text-prompter-text font-bold transition-all duration-300"
          style={{ fontSize: `${fontSize}px`, lineHeight: 1.3 }}
        >
          {currentSentence?.text || "End of presentation"}
        </div>

        {/* Next */}
        <div 
          className="absolute bottom-24 left-8 right-8 opacity-50 transition-all duration-500 line-clamp-3"
          style={{ fontSize: `${fontSize * 0.7}px`, lineHeight: 1.4 }}
        >
          {nextSentence?.text}
        </div>

      </div>

      {/* Controls */}
      <div className="flex justify-center items-center p-6 gap-6 bg-slate-900 border-t border-slate-700 pb-10">
        <button 
          onClick={reset}
          className="px-6 py-4 rounded-full bg-slate-700 text-white font-bold text-xl"
        >
          ↺ Reset
        </button>
        <button 
          onClick={togglePlay}
          className="px-12 py-4 rounded-full bg-prompter-accent text-black font-bold text-2xl w-48 text-center"
        >
          {isPlaying ? '⏸ Pause' : '▶ Start'}
        </button>
      </div>
    </div>
  );
}
